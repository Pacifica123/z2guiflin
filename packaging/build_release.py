#!/usr/bin/env python3
"""Explicit source allowlist -> reproducible, timestamp-free release tarball."""
from pathlib import Path
import argparse,gzip,hashlib,io,json,os,tarfile,re
ROOT=Path(__file__).resolve().parents[1]
ALLOWED_ROOTS={'core','gui','docs','tools','meta_tools','presets','profiles','strategies','runtime','themes','packaging'}
TOP_FILES={'README.md','LICENSE','pyproject.toml','run.sh'}
DENIED_PARTS={'.git','.zap2','__pycache__','.pytest_cache','node_modules','UserTestSpace','archives','patches','build','dist'}
DENIED_SUFFIXES={'.pyc','.pyo','.o','.a','.so','.dll','.exe','.sqlite','.sqlite3','.db'}
NATIVE_OUTPUTS={'core/zapret2/nfq2/nfqws2','core/zapret2/ip2net/ip2net','core/zapret2/mdig/mdig'}


def allowed(rel: str) -> bool:
    p=Path(rel)
    if p.is_absolute() or '..' in p.parts:return False
    if any(part in DENIED_PARTS or part=='.env' or part.startswith('.env.') for part in p.parts):return False
    if p.suffix in DENIED_SUFFIXES or rel in NATIVE_OUTPUTS or 'binaries/my' in rel:return False
    if len(p.parts)==1:return rel in TOP_FILES
    if p.parts[0] not in ALLOWED_ROOTS:return False
    if p.parts[:2]==('meta_tools','devctl'):return False
    # Historical frozen engineering receipts can describe captures; current
    # runtime/session/user evidence must never be a shipping resource.
    if p.parts[:2] in {('runtime','p05'),('runtime','p06'),('runtime','p07')} :return p.name=='pre-forensics.json'
    return True


def source_files(root: Path) -> list[Path]:
    index=json.loads((root/'packaging/release-files.json').read_text())
    if index.get('schemaVersion')!=1:raise ValueError('unknown source allowlist schema')
    names=index['files']
    if len(names)!=len(set(names)) or any(not allowed(n) for n in names):raise ValueError('unsafe source allowlist')
    files=[]
    for p in [root/n for n in sorted(names)]:
        rel=p.relative_to(root).as_posix()
        if not p.is_file():raise ValueError('missing release input: '+rel)
        if p.is_file() and allowed(rel):
            if p.is_symlink() or root.resolve() not in p.resolve().parents:raise ValueError('release symlink denied: '+rel)
            files.append(p)
    return files


def build(root: Path, output: Path) -> tuple[Path,dict]:
    version=re.search(r'^version\s*=\s*"([^"]+)"',(root/'pyproject.toml').read_text(),re.M).group(1)
    files=source_files(root)
    records={p.relative_to(root).as_posix():{'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'mode':0o755 if p.suffix=='.sh' or p.name=='zap2-runtime-executor' else 0o644} for p in files}
    digest=hashlib.sha256(json.dumps(records,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    manifest={'schemaVersion':1,'version':version,'releaseDigest':digest,'files':records,'service':'plan-only','ownership':'system package immutable; per-user workspace managed copies and user seeds'}
    output.parent.mkdir(parents=True,exist_ok=True)
    buffer=io.BytesIO()
    with tarfile.open(fileobj=buffer,mode='w',format=tarfile.USTAR_FORMAT) as tar:
        for rel in sorted([*records,'RELEASE_MANIFEST.json']):
            data=(json.dumps(manifest,sort_keys=True,indent=2)+'\n').encode() if rel=='RELEASE_MANIFEST.json' else (root/rel).read_bytes()
            info=tarfile.TarInfo('zap2gui-linux-'+version+'/'+rel);info.size=len(data);info.uid=info.gid=0;info.uname=info.gname='root';info.mtime=0;info.mode=records.get(rel,{'mode':0o644})['mode']
            tar.addfile(info,io.BytesIO(data))
    with output.open('wb') as handle:
        with gzip.GzipFile(fileobj=handle,mode='wb',filename='',mtime=0) as compressed:compressed.write(buffer.getvalue())
    return output,manifest


def arch_recipe(archive: Path,manifest: dict,output: Path):
    digest=hashlib.sha256(archive.read_bytes()).hexdigest()
    text=f'''# Generated by packaging/build_release.py; local pinned release input.
pkgname=zap2gui-linux
pkgver={manifest['version']}
pkgrel=1
pkgdesc='Zapret2 GUI with owned runtime and evidence diagnostics'
arch=('x86_64')
license=('MIT')
depends=('python>=3.10' 'python-pyqt6' 'nftables' 'sudo')
optdepends=('base-devel: native core build' 'pkgconf: native core build' 'zlib: native core build' 'libnetfilter_queue: native core build' 'libnfnetlink: native core build' 'libmnl: native core build' 'luajit: native core build' 'xray: optional VLESS backend')
source=('{archive.name}')
sha256sums=('{digest}')
package() {{
  python "$srcdir/zap2gui-linux-$pkgver/packaging/install_tree.py" --source "$srcdir/zap2gui-linux-$pkgver" --destdir "$pkgdir" --prefix /usr
}}
'''
    output.write_text(text)


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--root',type=Path,default=ROOT);parser.add_argument('--out',type=Path,required=True);parser.add_argument('--pkgbuild',type=Path)
    a=parser.parse_args();archive,manifest=build(a.root,a.out)
    if a.pkgbuild:arch_recipe(archive,manifest,a.pkgbuild)
    print(json.dumps({'archive':str(archive),'sha256':hashlib.sha256(archive.read_bytes()).hexdigest(),'releaseDigest':manifest['releaseDigest'],'files':len(manifest['files'])},indent=2))
if __name__=='__main__':main()
